/// Offline AI fallback — mirrors webapp `agentOfflineReply`.

String agentOfflineReply(String text) {
  final hits = <String>[];

  if (RegExp(r'ฟอกเงิน|เจ้าหน้าที่|ตำรวจ|ปปง|dsi|คดี', caseSensitive: false)
      .hasMatch(text)) {
    hits.add(
      'ลักษณะนี้ตรงกับกลลวง "ปลอมเป็นเจ้าหน้าที่ขู่คดีฟอกเงิน" ที่พบบ่อยที่สุด — '
      'หน่วยงานราชการจริงจะไม่มีวันขอให้โอนเงินหรือถอนเงินสดผ่านโทรศัพท์/วิดีโอคอลเพื่อ '
      '"ตรวจสอบความบริสุทธิ์" วางสายทันทีแล้วโทรกลับเบอร์ทางการของหน่วยงานเองเพื่อยืนยัน',
    );
  }
  if (RegExp(r'แฟน|ความรัก|โรแมนซ์|romance|ยืมเงิน|คู่รัก', caseSensitive: false)
      .hasMatch(text)) {
    hits.add(
      'หากคนที่คุยด้วยออนไลน์แต่ไม่เคยเจอตัวจริงขอยืมเงินหรือชวนลงทุน ให้สงสัยไว้ก่อนเสมอ — '
      'เป็นรูปแบบ Romance Scam ที่พบบ่อย อย่าโอนเงินก่อนตรวจสอบตัวตนได้จริง',
    );
  }
  if (RegExp(r'ลงทุน|กำไร|ผลตอบแทน|คริปโต|หุ้น|การันตี|สินทรัพย์ดิจิทัล')
      .hasMatch(text)) {
    hits.add(
      'การการันตีผลตอบแทนสูงคงที่หรือกำไรคริปโตโดยไม่มีความเสี่ยงขัดหลักการลงทุนพื้นฐาน '
      'ให้ตรวจสอบว่าแพลตฟอร์มได้รับอนุญาตจาก ก.ล.ต. หรือธนาคารแห่งประเทศไทยหรือไม่ก่อนตัดสินใจ — '
      'อย่าโอนเพิ่มเพื่อ "ปลดล็อก" หรือถอนกำไร',
    );
  }
  if (RegExp(r'งานเสริม|กดไลก์|ปลดล็อก|ค่าภารกิจ|เงินสำรอง|เปิดระบบ|แพ็กของ')
      .hasMatch(text)) {
    hits.add(
      'รูปแบบงานเสริมออนไลน์ที่ต้องโอนเงินก่อนหรือโอนเพิ่มเพื่อปลดล็อกระบบ เป็นกลโกงที่ ACSC เตือนซ้ำ — '
      'จำว่า "งานสบาย รายได้สูง ต้องโอนก่อน = มิจฉาชีพ 100%" หยุดโอนทันทีแล้วโทร AOC 1441',
    );
  }
  if (RegExp(r'วิดีโอคอล|กล้อง|ห้ามวางสาย').hasMatch(text)) {
    hits.add(
      'การถูกบังคับให้เปิดวิดีโอคอลค้างไว้นานและห้ามวางสาย คือสัญญาณอันตรายที่ควรวางสายทันที',
    );
  }
  if (RegExp(
    r'telegram|เทเลแกรม|ห้องสอบสวน|รหัสไลน์|รหัส line|otp|ค่าไถ่|คราบเลือด|เปลี่ยนเบอร์|ห้องรายวัน',
    caseSensitive: false,
  ).hasMatch(text)) {
    hits.add(
      'หากถูกชวนไปคุยใน Telegram หรือห้องชื่อ "ห้องสอบสวน" ถูกขอรหัสยืนยัน LINE '
      'ถูกสั่งให้ย้ายที่พักหรือเปลี่ยนเบอร์ หรือถูกสั่งให้ทำให้ครอบครัวเห็นว่าคุณถูกทำร้าย — '
      'นี่คือรูปแบบที่ข่าวเดือนตุลาคม 2569 รายงานไว้ อย่าส่งรหัส อย่าย้ายที่พักตามคำสั่ง '
      'วางสายแล้วโทร AOC 1441 หรือ 191 และบอกคนในครอบครัวด้วยช่องทางเดิม',
    );
  }

  if (hits.isEmpty) {
    hits.add(
      'ยังไม่สามารถระบุรูปแบบกลลวงที่ชัดเจนจากข้อความนี้ได้ — แนะนำให้ลองใช้เครื่องมือ '
      '"สแกนข้อความ" หรือ "ตรวจสอบวิดีโอคอล" เพื่อประเมินอย่างละเอียดขึ้น หรือหากรู้สึกไม่ปลอดภัย '
      'โทร 1441/191 ได้ทันที',
    );
  }

  return '${hits.join('\n\n')}\n\n'
      '(หมายเหตุ: นี่คือคำตอบจากระบบกฎคำสำคัญพื้นฐานแบบออฟไลน์ ไม่ใช่ AI เชิงสนทนาเต็มรูปแบบ)';
}
